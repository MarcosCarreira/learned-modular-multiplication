"""Recurrent scratchpad v2 — interleaved multiply-reduce (Horner) for TIER 3.

recurrent_v1 emitted `a*b = P ; P//p = k ; P%p = R` and stalled on tier 3 because
it couldn't generate the 10-digit product P (5x5 long multiplication) or the long
division. v2 sidesteps BOTH: it never forms the full product. Using Horner over
the digits of b,

    acc = 0
    for each digit b_i of b, MSB -> LSB:   acc = (acc*10 + a*b_i) mod p
    R = acc   after the last (LSB) digit

every step is small — multiply a by ONE digit (<=6 digits), shift, add, reduce
mod p (result < p). The algorithm is identical for every prime, so learning the
*steps* should generalize to tier-3 primes where table-memorization can't.

Scratchpad (all generated by the model from trained weights):
    BOS a SEP b SEP p SEP  m4 SEP acc4 SEP m3 SEP acc3 ... m0 SEP acc0 EOS
    m_i = a * (i-th digit of b),  acc_i = (acc_{i-1}*10 + m_i) mod p,  acc_0 = R

Compliance: the worked steps are TRAINING DATA (a teacher showing the algorithm),
not hand-coded forward logic. a%p, b%p are legal two-operand reductions; the
answer is the model's generated acc_0 (collapses under weight perturbation). No
sympy/Barrett/CRT/lookup in the forward pass. Digits LSB-first (carries flow).
"""
from __future__ import annotations

import os
from pathlib import Path

import torch
import torch.nn as nn
import torch.nn.functional as F

WIDTH = 5            # digits of a, b, p, acc   (covers p < 1e5 -> tiers 1-3)
MWIDTH = 6           # digits of m_i = a * single-digit  (<= 589815)
NB = WIDTH           # number of Horner steps = digits of b
LIMIT = 10 ** WIDTH

PAD, BOS, SEP, EOS = 10, 11, 12, 13
VOCAB = 14

# layout (fixed fields, SEP-separated; parsed by offset)
PROMPT_LEN = 1 + (WIDTH + 1) * 3                 # BOS a SEP b SEP p SEP
GROUP = (MWIDTH + 1) + (WIDTH + 1)               # m_i SEP acc_i SEP
GEN_LEN = GROUP * NB                              # NB groups (last SEP -> EOS)
SEQ_LEN = PROMPT_LEN + GEN_LEN
# offset of the FINAL acc (acc_0 = R) within the generated continuation:
R_OFF = GROUP * (NB - 1) + (MWIDTH + 1)           # skip NB-1 groups + last m field


def to_field(n: int, width: int) -> list[int]:
    out = []
    for _ in range(width):
        out.append(n % 10); n //= 10
    return out                       # LSB-first


def from_field(ids) -> int:
    v = 0
    for d in reversed(list(ids)):
        d = int(d)
        v = v * 10 + (d if 0 <= d <= 9 else 0)
    return v


def build_prompt(a: int, b: int, p: int) -> list[int]:
    return ([BOS] + to_field(a, WIDTH) + [SEP] + to_field(b, WIDTH)
            + [SEP] + to_field(p, WIDTH) + [SEP])


def build_full(a: int, b: int, p: int) -> list[int]:
    """Full teacher-forcing sequence with the interleaved Horner steps."""
    seq = build_prompt(a, b, p)
    acc = 0
    for i in range(NB - 1, -1, -1):           # MSB digit of b -> LSB
        bi = (b // (10 ** i)) % 10
        m = a * bi
        acc = (acc * 10 + m) % p
        seq += to_field(m, MWIDTH) + [SEP] + to_field(acc, WIDTH) + [SEP]
    seq[-1] = EOS                              # replace final SEP with EOS
    return seq


class ScratchpadDecoder(nn.Module):
    """Causal decoder-only transformer over the scratchpad vocabulary."""

    def __init__(self, d_model=256, nhead=8, num_layers=6, dim_ff=1024,
                 seq_len=SEQ_LEN):
        super().__init__()
        self.seq_len = seq_len
        self.tok_emb = nn.Embedding(VOCAB, d_model)
        self.pos_emb = nn.Embedding(seq_len, d_model)
        layer = nn.TransformerEncoderLayer(
            d_model=d_model, nhead=nhead, dim_feedforward=dim_ff,
            dropout=0.0, batch_first=True, activation="gelu")
        self.encoder = nn.TransformerEncoder(layer, num_layers=num_layers)
        self.ln = nn.LayerNorm(d_model)
        self.head = nn.Linear(d_model, VOCAB)
        self.register_buffer("pos_ids", torch.arange(seq_len), persistent=False)
        self.config = dict(d_model=d_model, nhead=nhead, num_layers=num_layers,
                           dim_ff=dim_ff, seq_len=seq_len)

    def forward(self, tokens: torch.Tensor) -> torch.Tensor:
        L = tokens.shape[1]
        x = self.tok_emb(tokens) + self.pos_emb(self.pos_ids[:L].unsqueeze(0))
        mask = torch.triu(torch.full((L, L), float("-inf"), device=tokens.device), 1)
        x = self.ln(self.encoder(x, mask=mask))
        return self.head(x)

    @torch.no_grad()
    def _generate_uncached(self, prompt: torch.Tensor, steps: int) -> torch.Tensor:
        seq = prompt
        for _ in range(steps):
            nxt = self.forward(seq)[:, -1, :].argmax(-1, keepdim=True)
            seq = torch.cat([seq, nxt], dim=1)
        return seq[:, prompt.shape[1]:]

    # ---- KV-cached generation (≈5x faster; falls back if it ever disagrees) ----
    def _layer_step(self, layer, x, Kc, Vc):
        """One post-norm encoder layer with K/V cache. x:(B,T_new,d)."""
        attn = layer.self_attn
        H, d = attn.num_heads, x.shape[-1]
        dh = d // H
        qkv = F.linear(x, attn.in_proj_weight, attn.in_proj_bias)
        q, k, v = qkv.split(d, dim=-1)
        sh = lambda t: t.view(x.shape[0], -1, H, dh).transpose(1, 2)  # (B,H,T,dh)
        q, k, v = sh(q), sh(k), sh(v)
        if Kc is not None:
            k = torch.cat([Kc, k], dim=2); v = torch.cat([Vc, v], dim=2)
        att = (q @ k.transpose(-2, -1)) / (dh ** 0.5)               # (B,H,Tnew,Tall)
        Tnew, Tall = q.shape[2], k.shape[2]
        i = torch.arange(Tnew, device=x.device).unsqueeze(1) + (Tall - Tnew)
        j = torch.arange(Tall, device=x.device).unsqueeze(0)
        att = att.masked_fill(j > i, float("-inf")).softmax(-1)
        o = (att @ v).transpose(1, 2).reshape(x.shape[0], Tnew, d)
        o = F.linear(o, attn.out_proj.weight, attn.out_proj.bias)
        x = layer.norm1(x + o)
        x = layer.norm2(x + layer.linear2(F.gelu(layer.linear1(x))))
        return x, k, v

    @torch.no_grad()
    def generate_cached(self, prompt: torch.Tensor, steps: int) -> torch.Tensor:
        layers = list(self.encoder.layers)
        Kc = [None] * len(layers); Vc = [None] * len(layers)
        Lp = prompt.shape[1]
        x = self.tok_emb(prompt) + self.pos_emb(self.pos_ids[:Lp].unsqueeze(0))
        for li, lyr in enumerate(layers):
            x, Kc[li], Vc[li] = self._layer_step(lyr, x, None, None)
        nxt = self.head(self.ln(x[:, -1:, :])).argmax(-1)
        gen = [nxt]; pos = Lp
        for _ in range(steps - 1):
            x = self.tok_emb(nxt) + self.pos_emb(self.pos_ids[pos:pos + 1].unsqueeze(0))
            for li, lyr in enumerate(layers):
                x, Kc[li], Vc[li] = self._layer_step(lyr, x, Kc[li], Vc[li])
            nxt = self.head(self.ln(x[:, -1:, :])).argmax(-1)
            gen.append(nxt); pos += 1
        return torch.cat(gen, dim=1)

    @torch.no_grad()
    def _verify_cache(self, dev) -> bool:
        try:
            L = max(4, self.seq_len // 4)
            p = torch.randint(0, VOCAB, (3, L), device=dev)
            ok = torch.equal(self._generate_uncached(p, 10), self.generate_cached(p, 10))
            print(f"[KV-cache] {'verified == uncached; fast path on' if ok else 'MISMATCH -> using uncached'}",
                  flush=True)
            return bool(ok)
        except Exception as e:  # noqa: BLE001
            print(f"[KV-cache] error ({e}); using uncached", flush=True)
            return False

    @torch.no_grad()
    def generate(self, prompt: torch.Tensor, steps: int) -> torch.Tensor:
        if getattr(self, "_cache_ok", None) is None:
            self._cache_ok = self._verify_cache(prompt.device)
        return (self.generate_cached if self._cache_ok else self._generate_uncached)(prompt, steps)


from modchallenge.interface.base_model import ModularMultiplicationModel  # noqa: E402


class ScratchpadModel(ModularMultiplicationModel):
    def __init__(self):
        self.model: ScratchpadDecoder | None = None
        self.device: torch.device | None = None

    def load(self, model_dir: str) -> None:
        if os.environ.get("MODCH_FORCE_CPU") == "1":
            self.device = torch.device("cpu")
        elif torch.backends.mps.is_available():
            self.device = torch.device("mps")
        elif torch.cuda.is_available():
            self.device = torch.device("cuda")
        else:
            self.device = torch.device("cpu")
        ckpt = torch.load(Path(model_dir) / "weights.pt",
                          map_location=self.device, weights_only=True)
        self.model = ScratchpadDecoder(**ckpt.get("config", {}))
        self.model.load_state_dict(ckpt["state_dict"])
        self.model.to(self.device)
        self.model.eval()

    def preprocess_a(self, a):
        return a

    def preprocess_b(self, b):
        return b

    def preprocess_p(self, p):
        return p

    @torch.no_grad()
    def predict_digits(self, a_enc, b_enc, p_enc):
        return self.predict_digits_batch([(a_enc, b_enc, p_enc)])[0]

    @torch.no_grad()
    def predict_digits_batch(self, inputs):
        assert self.model is not None
        out: list[list[int] | None] = [None] * len(inputs)
        prompts, idx = [], []
        for i, (a_enc, b_enc, p_enc) in enumerate(inputs):
            p = int(p_enc)
            if not (2 <= p < LIMIT):
                out[i] = [0]
                continue
            a_red = int(a_enc) % p
            b_red = int(b_enc) % p
            prompts.append(build_prompt(a_red, b_red, p))
            idx.append(i)
        if idx:
            pt = torch.tensor(prompts, dtype=torch.long, device=self.device)
            gen = self.model.generate(pt, GEN_LEN).cpu().tolist()
            for j, i in enumerate(idx):
                R = from_field(gen[j][R_OFF:R_OFF + WIDTH])     # acc_0 = answer
                out[i] = [int(d) for d in str(R)]
        return [o if o is not None else [0] for o in out]

    def max_batch_size(self) -> int:
        return 256
